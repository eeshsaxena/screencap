/**
 * Injects the non-secret cloud-auth client credentials into a built extension,
 * mirroring `scripts/generate_provisioned.py` in the Python layer.
 *
 * Runs AFTER `tsc` and overwrites the compiled output of
 * `src/auth/provisioned.ts` — the source module stays committed with
 * placeholders so a plain checkout still typechecks, tests, and builds. That is
 * the one structural difference from the Python original, which can simply omit
 * its `_provisioned` module because Python catches `ImportError` at runtime.
 *
 * Fails closed: a run missing either variable writes nothing and exits non-zero,
 * so a build that forgot to source the values cannot produce a package whose
 * every sign-in dies at Google with an opaque error. The release guard
 * (`verify-provisioned.mjs`) is the net that catches the same failure from the
 * other side, on the built output.
 *
 * Usage (from `extension/`, after `npm run build`):
 *
 *     SCREENCAP_FIREBASE_API_KEY=... SCREENCAP_EXTENSION_OAUTH_CLIENT_ID=... \
 *         node scripts/generate-provisioned.mjs
 *
 * Neither value is confidential — a Firebase Web API key and an OAuth client id
 * are public identifiers, and the Web-client implicit flow bundles no client
 * secret at all. "Inject, don't commit" keeps them out of git; it is not a
 * security boundary. See `docs/runbooks/cloud-auth-setup.md`.
 */
import { realpathSync } from "node:fs";
import { mkdir, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Deliberately distinct from the CLI's `SCREENCAP_OAUTH_CLIENT_ID`, which
 * carries the Google **Desktop** client id. Both live in the same `.env` and
 * the same Secrets namespace, and bundling the desktop id here would not fail
 * the build — it would fail at sign-in with an opaque audience mismatch.
 */
export const OAUTH_CLIENT_ID_ENV = "SCREENCAP_EXTENSION_OAUTH_CLIENT_ID";

/** The same Firebase project the CLI authenticates against, so the same key. */
export const FIREBASE_API_KEY_ENV = "SCREENCAP_FIREBASE_API_KEY";

/** Relative to the build output root; mirrors `src/auth/provisioned.ts`. */
export const OUTPUT_RELATIVE_PATH = "auth/provisioned.js";

const EXTENSION_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

const HEADER = `// AUTO-GENERATED by scripts/generate-provisioned.mjs — DO NOT EDIT, DO NOT COMMIT.
//
// Build-time-injected, non-secret cloud-auth client credentials, overwriting the
// compiled output of src/auth/provisioned.ts. Lives only in the build output,
// which is gitignored. Regenerate by re-running the packaging command.
`;

/**
 * Write the injected module, or report what was missing.
 *
 * Separated from the CLI wrapper so the failure paths — the ones worth
 * testing — can be exercised by calling this directly rather than spawning a
 * subprocess per scenario to read an exit code.
 *
 * @param {{ env: Record<string, string | undefined>, distDir: string }} options
 * @returns {Promise<{ ok: boolean, missing: string[], outputPath: string }>}
 */
export async function generateProvisioned({ env, distDir }) {
  const apiKey = (env[FIREBASE_API_KEY_ENV] ?? "").trim();
  const clientId = (env[OAUTH_CLIENT_ID_ENV] ?? "").trim();
  const outputPath = join(distDir, OUTPUT_RELATIVE_PATH);

  // Remove any prior output FIRST, so a fail-closed exit can never leave an
  // earlier run's (possibly rotated) values in a gitignored build directory to
  // be silently re-packaged.
  await rm(outputPath, { force: true });

  const missing = [
    [FIREBASE_API_KEY_ENV, apiKey],
    [OAUTH_CLIENT_ID_ENV, clientId],
  ]
    .filter(([, value]) => !value)
    .map(([name]) => name);

  if (missing.length > 0) return { ok: false, missing, outputPath };

  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(
    outputPath,
    `${HEADER}
export const FIREBASE_API_KEY = ${JSON.stringify(apiKey)};
export const OAUTH_CLIENT_ID = ${JSON.stringify(clientId)};
`,
    "utf8",
  );
  return { ok: true, missing: [], outputPath };
}

/**
 * True when this module is being run as a script rather than imported.
 *
 * Compares real paths rather than `import.meta.url` against an interpolated
 * `file://` + `argv[1]`, which diverges both on encoding (Node percent-encodes
 * the URL, argv is raw) and on symlinks (Node resolves the URL, argv keeps the
 * path as invoked — so anything under macOS `/tmp` or `/var` breaks). Getting it
 * wrong here means exiting 0 having injected nothing. See the fuller note in
 * `verify-provisioned.mjs`.
 */
function isMain() {
  if (process.argv[1] === undefined) return false;
  try {
    return realpathSync(process.argv[1]) === fileURLToPath(import.meta.url);
  } catch {
    return false;
  }
}

if (isMain()) {
  const { ok, missing, outputPath } = await generateProvisioned({
    env: process.env,
    distDir: join(EXTENSION_ROOT, "dist"),
  });

  if (!ok) {
    const names = missing.join(", ");
    // GitHub Actions annotation on stdout so a failed release surfaces the
    // cause inline rather than as a bare non-zero exit.
    console.log(
      `::error::generate-provisioned.mjs: missing required environment variable(s): ${names}. ` +
        "Set them before packaging (see docs/runbooks/cloud-auth-setup.md).",
    );
    console.error(
      `ERROR: refusing to inject credentials — missing required environment variable(s): ${names}.\n` +
        "Set both before packaging (see docs/runbooks/cloud-auth-setup.md).",
    );
    process.exit(1);
  }

  // The path only — never the values.
  console.log(`Wrote ${outputPath}`);
}
